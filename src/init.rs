use anyhow::{Context, Result, bail};
use std::fs;
use std::path::Path;

/// Starter `.proj-janitor.toml` written by `projjan init`.
pub(crate) const INIT_CONFIG_TEMPLATE: &str = r#"# Generated by `projjan init`.
# Priority: command-line flags > environment variables > this file > built-ins.
# Uncomment and edit the keys you need. Unknown keys are rejected.

[backup]
# dest = "/data/backups"
# keep = 3
# exclude = ["node_modules", "*.log", "target"]
# incremental = false
# progress = true
# check_space = true
# fail_on_secrets = false
# exclude_secrets = false
# fail_on_insecure_dest = false
# encrypt_passphrase_file = "/path/to/passphrase"

[prune]
# keep = 3

[verify]
# check_remote = false
# progress = true

[restore]
# check_remote = false
# require_dest = false
# force = false
# continue_on_error = false
# skip_existing = false
# progress = true
# decrypt_passphrase_file = "/path/to/passphrase"
"#;

pub(crate) fn init_config(directory: &Path, force: bool) -> Result<std::path::PathBuf> {
    let dir = crate::expand(directory);
    if !dir.exists() {
        fs::create_dir_all(&dir)
            .with_context(|| format!("cannot create directory {}", dir.display()))?;
    }
    if !dir.is_dir() {
        bail!("destination is not a directory: {}", dir.display());
    }
    let path = dir.join(crate::config::CONFIG_NAME);
    if path.exists() && !force {
        bail!(
            "config already exists: {} (pass --force to overwrite)",
            path.display()
        );
    }
    fs::write(&path, INIT_CONFIG_TEMPLATE)
        .with_context(|| format!("cannot write {}", path.display()))?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};

    static NEXT_TEMP: AtomicU32 = AtomicU32::new(0);

    struct TempDir(std::path::PathBuf);
    impl TempDir {
        fn new() -> Self {
            let path = std::env::temp_dir().join(format!(
                "projjan-init-test-{}-{}",
                std::process::id(),
                NEXT_TEMP.fetch_add(1, Ordering::Relaxed)
            ));
            fs::create_dir_all(&path).unwrap();
            Self(path)
        }
    }
    impl Drop for TempDir {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn init_writes_starter_config() {
        let temp = TempDir::new();
        let path = init_config(&temp.0, false).unwrap();
        assert_eq!(path, temp.0.join(crate::config::CONFIG_NAME));
        let text = fs::read_to_string(&path).unwrap();
        assert!(text.contains("[backup]"));
        assert!(text.contains("[restore]"));
        assert!(text.contains("Generated by `projjan init`"));
        let err = init_config(&temp.0, false).unwrap_err().to_string();
        assert!(err.contains("config already exists"));
        assert!(err.contains("--force"));
        let path2 = init_config(&temp.0, true).unwrap();
        assert_eq!(path2, path);
    }
}
